"""造一份较长的文学体测试 docx,用于看 L2 报告密度是否合理。"""
from pathlib import Path
from docx import Document


def make(path: Path):
    doc = Document()
    doc.add_heading("散文:小镇的春天", level=1)

    paragraphs = [
        # 段 1-3:正常文学段,应该几乎不报
        "春天来到这座小镇的时候,街道两旁的杨树才刚刚抽出新芽。奶奶坐在门前的石凳上,眯起眼睛望着远处的山。她总是这样,在每一个清晨的阳光里。",
        "我从城里回来,行李还没放下,就听到隔壁院子传来熟悉的鸡叫声。这声音让我想起小时候,想起那些在乡下度过的漫长夏天。",
        "母亲在厨房里忙着,锅里炖着的是我最爱吃的红烧肉。她头也不抬地问:'路上累不累?'我说不累,其实从早晨出门到现在,已经过去了八个小时。",
        # 段 4-6:正常段,叙事,夹一些可能"看似冗余"但实际是文学化的
        "院子里的那棵老槐树还在,树皮粗糙,枝桠向四面八方伸展。我记得小时候爬到树上去摘槐花,被父亲发现后大骂一顿。现在父亲已经不在了,槐树却还活着。",
        "村口的小卖部换了招牌,从'供销社'变成了某品牌便利店的加盟点。门口坐着的老人却还是那几个,他们看见我,慢慢地、慢慢地认出来,然后笑着打招呼。",
        "傍晚的时候我去河边走了走。河水比记忆中浅了许多,水面上漂着塑料瓶和泡沫盒。一群孩子在浅水处玩闹,他们的笑声像极了二十年前的我们。",
        # 段 7-8:故意放一个真的拗口 + 一个真的重复
        "对于这件事情进行的讨论是在一个非常匆忙的状态之下完成的所以结果并不是非常的令人满意。",  # 真拗口
        "她说她已经告诉过我她要走的事情她不想再说她要走的事情。",  # 真用词重复
        # 段 9-12:更多正常段
        "晚饭后,母亲拉着我的手坐在院子里,絮絮叨叨地讲这一年里村子的事——谁家盖了新房,谁家的孩子考上了大学,谁家的老人去世了。",
        "夜风从远处的麦田吹过来,带着一种说不出的清香。星星很亮,比城里见到的多得多。我抬头看了很久,忽然觉得鼻子有些酸。",
        "第二天清晨,我被一阵雨声唤醒。雨不大,落在屋檐上,落在院子的青砖上,发出细细密密的声音。我在床上躺了一会儿,然后起身,推开窗户。",
        "窗外的世界是湿漉漉的。空气清新到让人想深吸一口。母亲已经起来了,在厨房里热着早餐。我闻到了小米粥的香味。",
    ]
    for p in paragraphs:
        doc.add_paragraph(p)

    doc.save(str(path))
    print(f"已生成: {path}")
    print(f"段落数: {len(paragraphs)}, 总字数: {sum(len(p) for p in paragraphs)}")


if __name__ == "__main__":
    make(Path(__file__).parent / "fixtures" / "长文测试.docx")
