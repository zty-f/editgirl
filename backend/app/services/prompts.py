# ============================================================================
# L1 词典上下文(注入到 L2/L3 prompt,让 LLM 知道哪些已被规则覆盖)
# ============================================================================
def l1_dictionary_context(idiom_errors: dict, homophone_errors: dict, max_idioms: int = 20) -> str:
    sample = list(idiom_errors.items())[:max_idioms]
    sample_str = "、".join(f"{w}→{r}" for w, r in sample)
    homo_str = "、".join(f"{w}→{r}" for w, r in homophone_errors.items())
    return f"""

【L1 规则引擎已覆盖(规则=瞬间命中,你别重报)】
- {len(idiom_errors)} 条成语错字示例:{sample_str}
- {len(homophone_errors)} 条同音字:{homo_str}
- 中文段里英文标点(,;:?!)、全角字母数字、中文间多余空格

→ 性质相同但**不在词典里**的成语错字/同音字,你可以**补报**(layer="L1", type="成语错别字" 或 "同音字", confidence="high")。"""


# ============================================================================
# Helper:把多段拼成 prompt user 块
# ============================================================================
def format_paragraphs_block(segs: list[tuple[int, str]]) -> str:
    """[(idx, text), ...] → '【段 0】\\n...\\n\\n【段 1】\\n...'"""
    parts = []
    for idx, text in segs:
        parts.append(f"【段 {idx}】\n{text}")
    return "\n\n".join(parts)


def format_document_block(paragraphs: list[str]) -> str:
    """整文用 L4。"""
    return "\n".join(f"【段 {i}】{t}" for i, t in enumerate(paragraphs) if t.strip())


